-- Wina Bwangu Database — Dashboard Queries
-- Each query below maps to one requirement in the case study (a–j)
-- =====================================================================

USE wina_bwangu;

-- (c) Given a booth, show only the services that booth is allowed to sell,
--     with the revenue-per-kwacha for each.
--     Replace 'Wina3' with whatever the user picks in the dropdown.
SELECT s.service_name, s.rate AS revenue_per_kwacha
FROM   booth_services bs
JOIN   services s ON s.service_name = bs.service_name
WHERE  bs.booth_code = 'Wina3';

-- (d) Transaction Amount after Tax for every transaction.
--     Tax is charged on the commission Wina Bwangu earns, i.e.
--     commission = amount * rate, tax = commission * 0.16.
SELECT t.transaction_id,
       t.transaction_amount,
       (t.transaction_amount * s.rate)                         AS commission,
       (t.transaction_amount * s.rate) * 0.16                  AS tax,
       t.transaction_amount - ((t.transaction_amount * s.rate) * 0.16) AS amount_after_tax
FROM   transactions t
JOIN   services s ON s.service_name = t.service_name;

-- (f) Cumulative Total and Amount Remaining from the Monthly Limit,
--     per service — this is what tells an agent whether there's still
--     credit available to approve a new transaction.
SELECT s.service_name,
       s.month_limit,
       COALESCE(SUM(t.transaction_amount), 0)                     AS cumulative_total,
       s.month_limit - COALESCE(SUM(t.transaction_amount), 0)     AS amount_remaining
FROM   services s
LEFT JOIN transactions t ON t.service_name = s.service_name
GROUP BY s.service_name, s.month_limit
ORDER BY s.service_name;

-- (g) Cumulative Revenue per Mobile Booth (commission earned, not raw
--     transaction value — "revenue" for Wina Bwangu is the commission).
SELECT b.booth_code,
       b.location,
       COALESCE(SUM(t.transaction_amount * s.rate), 0) AS cumulative_revenue
FROM   booths b
LEFT JOIN transactions t ON t.booth_code = b.booth_code
LEFT JOIN services s     ON s.service_name = t.service_name
GROUP BY b.booth_code, b.location
ORDER BY cumulative_revenue DESC;

-- (h) Frequency of each Service at each Mobile Booth (count of transactions).
SELECT t.booth_code, t.service_name, COUNT(*) AS frequency
FROM   transactions t
GROUP BY t.booth_code, t.service_name
ORDER BY t.booth_code, t.service_name;

-- (i-i) Total Revenue generated by the company overall (sum of commission
--       across every transaction).
SELECT ROUND(SUM(t.transaction_amount * s.rate), 2) AS total_revenue
FROM   transactions t
JOIN   services s ON s.service_name = t.service_name;

-- (i-ii) Total Capital required per month — sum of the monthly limits
--        across all services (the credit the business must hold ready).
SELECT SUM(month_limit) AS total_capital
FROM   services;

-- (j) Data for the Pie Chart — revenue share by service (feed this
--     straight into whatever charting library you use client-side).
SELECT s.service_name,
       ROUND(SUM(t.transaction_amount * s.rate), 2) AS revenue
FROM   transactions t
JOIN   services s ON s.service_name = t.service_name
GROUP BY s.service_name
ORDER BY revenue DESC;

-- Sanity check: total number of transactions loaded (case study says 308).
SELECT COUNT(*) AS total_transactions FROM transactions;
